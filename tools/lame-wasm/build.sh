#!/usr/bin/env bash
# Rebuilds src/audio/lame/lameWasm.ts: the LAME MP3 encoder compiled to WebAssembly.
# Needs clang with the wasm32 target and wasm-ld (no emscripten, no wasi sysroot: libc.c is the whole C library).
# LAME is LGPL-2.1+. Upstream source: https://github.com/gypified/libmp3lame (LAME 3.99), pinned below. It is used unmodified.
set -euo pipefail
LAME_COMMIT=${LAME_COMMIT:-$(cat "$(dirname "$0")/LAME_COMMIT")}
HERE=$(cd "$(dirname "$0")" && pwd)
WORK=$(mktemp -d)
git clone --quiet https://github.com/gypified/libmp3lame "$WORK/lame"
git -C "$WORK/lame" checkout --quiet "$LAME_COMMIT"
mkdir -p "$WORK/src"
cp "$WORK"/lame/libmp3lame/*.c "$WORK"/lame/libmp3lame/*.h "$WORK/lame/include/lame.h" "$WORK/src/"
rm "$WORK/src/mpglib_interface.c" "$WORK/src/xmm_quantize_sub.c" 2>/dev/null || true
cp "$HERE/libc.c" "$HERE/wrap.c" "$WORK/src/"
cd "$WORK"
for f in src/*.c; do
  clang --target=wasm32 -O3 -msimd128 -flto -ffreestanding -nostdlib -fvisibility=hidden -DHAVE_CONFIG_H -DNDEBUG \
    -I "$HERE/inc" -I src -Wno-everything -c "$f" -o "$(basename "$f" .c).o"
done
wasm-ld --no-entry --allow-undefined --strip-all --gc-sections -z stack-size=1048576 --initial-memory=8388608 \
  --export=enc_create --export=enc_left --export=enc_right --export=enc_out --export=enc_encode --export=enc_flush --export=enc_close --export=memory \
  -o lame.wasm ./*.o
{
  echo "// Generated by tools/lame-wasm/build.sh from LAME ($LAME_COMMIT). Do not edit."
  echo "export const LAME_WASM_BASE64 = '$(base64 -w0 lame.wasm)';"
} > "$HERE/../../src/audio/lame/lameWasm.ts"
echo "wrote src/audio/lame/lameWasm.ts ($(wc -c < lame.wasm) bytes of wasm)"
